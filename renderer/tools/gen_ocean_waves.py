"""Generate shaders/ocean_waves.glsl and its CPU copy src/ocean_waves.h: a deterministic set of deep-water waves sampled from a JONSWAP wind-sea
spectrum with cos-2s directional spreading (the spectrum model of gasgiant/FFT-Ocean, MIT, Ivan Pensionerov),
summed directly in the shaders instead of through an FFT.

    python tools/gen_ocean_waves.py            # rewrite the include
    python tools/gen_ocean_waves.py --self-test
"""
import math
import random
import sys
from pathlib import Path

G = 9.81
WIND_SPEED = 18.0      # m/s
FETCH = 300_000.0      # m
WIND_ANGLE = 0.35      # radians from +x; the flight heads +z, so the sea crosses it
GAMMA = 2.2            # broader peak so distant water is not dominated by parallel swell
CHOP = 0.32            # leave room for the travelling groups' 1.68x peak amplitude and gradient
SHORT_WAVES_FADE = 0.25  # m; FFT-Ocean's exp(-(fade*k)^2) damping of short waves, so close water reads smooth
# (count, lowest omega, highest omega): displaced swell first, then shading-only short waves.
BANDS = [(80, 0.35, 4.5), (64, 4.5, 22.0)]


def jonswap(omega):
    alpha = 0.076 * (G * FETCH / WIND_SPEED ** 2) ** -0.22
    peak = 22.0 * (WIND_SPEED * FETCH / G ** 2) ** -0.33
    sigma = 0.07 if omega <= peak else 0.09
    r = math.exp(-(omega - peak) ** 2 / (2 * sigma ** 2 * peak ** 2))
    return alpha * G ** 2 * omega ** -5 * math.exp(-1.25 * (peak / omega) ** 4) * GAMMA ** r, peak


def spread_power(omega, peak):
    return 9.77 * (omega / peak) ** -2.5 if omega > peak else 6.97 * (omega / peak) ** 5


def sample_direction(rng, s):
    # Rejection-sample cos^(2s)(theta/2) around the wind.
    while True:
        theta = rng.uniform(-math.pi, math.pi)
        if rng.random() <= abs(math.cos(theta / 2)) ** (2 * s):
            return WIND_ANGLE + theta


def waves():
    rng = random.Random(20261011)
    result = []
    for count, low, high in BANDS:
        for i in range(count):
            # Log-spaced bands, jittered inside each band.
            a, b = low * (high / low) ** (i / count), low * (high / low) ** ((i + 1) / count)
            omega = math.exp(rng.uniform(math.log(a), math.log(b)))
            spectrum, peak = jonswap(omega)
            k = omega * omega / G
            amplitude = math.sqrt(2 * spectrum * (b - a)) * math.exp(-(SHORT_WAVES_FADE * k) ** 2)
            angle = sample_direction(rng, max(spread_power(omega, peak) * .55, .65))
            # Cross seas break up long parallel wavefronts without increasing the total spectral energy.
            if i % 3 == 1:
                angle += 1.45
            result.append((math.cos(angle), math.sin(angle), k, amplitude, rng.uniform(0, 2 * math.pi)))
    return result


def write(path):
    data = waves()
    displaced = BANDS[0][0]
    lines = ['// Generated by tools/gen_ocean_waves.py; do not edit. JONSWAP wind sea, '
             f'U={WIND_SPEED} m/s, fetch={FETCH / 1000:.0f} km, chop={CHOP}.',
             f'const int OCEAN_WAVES = {len(data)};',
             f'const int OCEAN_DISPLACED = {displaced}; // the first waves move vertices; the rest only shade',
             f'const float OCEAN_CHOP = {CHOP};',
             '// direction x, direction z, wavenumber k (rad/m), amplitude (m); phase offsets separately.',
             'const vec4 oceanWaves[OCEAN_WAVES] = vec4[](']
    lines += [f'    vec4({w[0]:.5f}, {w[1]:.5f}, {w[2]:.6f}, {w[3]:.6f}){"," if i + 1 < len(data) else ""}' for i, w in enumerate(data)]
    lines += [');', 'const float oceanPhases[OCEAN_WAVES] = float[](']
    lines += ['    ' + ', '.join(f'{w[4]:.4f}' for w in data[i:i + 8]) + (',' if i + 8 < len(data) else '') for i in range(0, len(data), 8)]
    lines += [');', '']
    Path(path).write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def write_header(path):
    data = waves()
    lines = ['// Generated by tools/gen_ocean_waves.py; do not edit. CPU copy of shaders/ocean_waves.glsl,',
             '// so a ship can ride the rendered sea.',
             '#pragma once',
             f'constexpr int OceanWaveCount = {len(data)}, OceanDisplaced = {BANDS[0][0]};',
             f'constexpr float OceanChop = {CHOP}f;',
             'struct OceanWave { float dx, dz, k, amplitude, phase; };',
             'constexpr OceanWave oceanWaveTable[OceanWaveCount] = {']
    lines += [f'    {{{w[0]:.5f}f, {w[1]:.5f}f, {w[2]:.6f}f, {w[3]:.6f}f, {w[4]:.4f}f}},' for w in data]
    lines += ['};', '']
    Path(path).write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def self_test():
    data = waves()
    assert data == waves(), 'deterministic'
    assert len(data) == sum(count for count, _, _ in BANDS)
    significant = 4 * math.sqrt(sum(w[3] ** 2 / 2 for w in data))
    assert 4.5 < significant < 8.0, f'significant wave height {significant:.2f} m outside the rough-sea target'
    folding = sum(w[2] * w[3] * CHOP for w in data[:BANDS[0][0]])
    # Bound both the amplified displacement derivative and the group's product-rule term.
    group_gradient = .48 * (math.hypot(.011, .007) + math.hypot(.006, .013))
    grouped_folding = 1.68 * folding + group_gradient * CHOP * sum(w[3] for w in data[:BANDS[0][0]])
    assert grouped_folding < 1.0, f'grouped displaced crests would loop ({grouped_folding:.2f})'
    # Both horizontal directions need slope energy; otherwise the aerial view becomes parallel stripes.
    xx = sum((w[0] * w[2] * w[3]) ** 2 for w in data)
    zz = sum((w[1] * w[2] * w[3]) ** 2 for w in data)
    xz = sum(w[0] * w[1] * (w[2] * w[3]) ** 2 for w in data)
    split = math.sqrt((xx - zz) ** 2 + 4 * xz ** 2)
    spread = (xx + zz - split) / (xx + zz + split)
    assert spread > .35, f'wave slopes too directional ({spread:.2f})'
    print(f'gen_ocean_waves self-test passed: base Hs {significant:.2f} m, grouped chop bound {grouped_folding:.2f}, directional ratio {spread:.2f}')


if __name__ == '__main__':
    if sys.argv[1:] == ['--self-test']:
        self_test()
    else:
        root = Path(__file__).resolve().parent.parent
        write(root / 'shaders' / 'ocean_waves.glsl')
        write_header(root / 'src' / 'ocean_waves.h')
